export const UI_COPY: Readonly<Record<UiLanguage, UiCopy>> = { zh, en };

export function localizeRendererLabel(language: UiLanguage, label: string): string {
  if (language === 'en') return label;
  return label
    .replace('GPU Sort', 'GPU 排序')
    .replace('CPU Sort', 'CPU 排序')
    .replace('Worker Sort', 'Worker 排序');
}

export function localizeRuntimeMessage(language: UiLanguage, message?: string): string | undefined {
  if (!message || language === 'zh') return message;
  const directMessages: Readonly<Record<string, string>> = {
    '正在打开 RAW4D 文件': 'Opening RAW4D file',
    '正在读取 RAW4D 头部': 'Reading RAW4D header',
    '正在建立 4D 关键帧轨迹': 'Building 4D keyframe tracks',
    'RAW4D 解析完成': 'RAW4D parsing complete',
    '系统内存已驻留': 'resident in system memory',
    '正在写入长期 GPUBuffer 并建立 GPU 解码路径': 'Uploading persistent GPU buffers and preparing GPU decode',
    '三维视口尚未初始化完成。': 'The 3D viewport is not ready.',
  };
  if (directMessages[message]) return directMessages[message];
  const gaussianProgress = /^正在读取高斯数据 (\d+)%$/.exec(message);
  if (gaussianProgress) return `Reading Gaussian data ${gaussianProgress[1]}%`;
  // #WDD-gpt 2026-08-16 - 4CGS Worker 心跳包含动态任务与耗时，英文界面按结构翻译而不是泄漏中文状态。
  const fourCgsWorkers = /^(\d+) 个子 Worker · (\d+)\/(\d+) 项完成 · 正在处理 (.+) · ([\d.]+) 秒$/.exec(message);
  if (fourCgsWorkers) {
    const labels: Readonly<Record<string, string>> = {
      位置: 'Position', 旋转: 'Rotation', 缩放: 'Scale', DC: 'DC', 透明度: 'Opacity', 生命周期: 'Lifetime', SH: 'SH', 收尾: 'finalization',
    };
    const remainingMatch = /^(.+?)(?:等 (\d+) 项)?$/.exec(fourCgsWorkers[4]);
    const visible = (remainingMatch?.[1] ?? fourCgsWorkers[4]).split('、').map((label) => labels[label] ?? label);
    const totalRemaining = Number(remainingMatch?.[2] ?? visible.length);
    const hidden = Math.max(0, totalRemaining - visible.length);
    const remaining = `${visible.join(', ')}${hidden ? ` and ${hidden} more` : ''}`;
    return `${fourCgsWorkers[1]} subworkers · ${fourCgsWorkers[2]}/${fourCgsWorkers[3]} attributes complete · Processing ${remaining} · ${fourCgsWorkers[5]}s`;
  }
  // #WDD-gpt 2026-08-16 - 后续片段提取和 Loader 池进度同样保持中英文界面一致。
  const fourCgsExtraction = /^正在并行提取 4CGS 片段 (\d+)\/(\d+)$/.exec(message);
  if (fourCgsExtraction) return `Extracting 4CGS segments ${fourCgsExtraction[1]}/${fourCgsExtraction[2]}`;
  const loaderPool = /^(\d+) 个 Loader Worker · (\d+)\/(\d+) 段完成 · (.+?) · (.+)$/.exec(message);
  if (loaderPool) {
    const detail = localizeRuntimeMessage('en', loaderPool[5]) ?? loaderPool[5];
    return `${loaderPool[1]} Loader Workers · ${loaderPool[2]}/${loaderPool[3]} segments complete · ${loaderPool[4]} · ${detail}`;
  }
  return message;
}
