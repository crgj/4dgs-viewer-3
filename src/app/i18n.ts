export function localizeRendererLabel(language: UiLanguage, label: string): string {
  if (language === 'en') return label;
  return label
    .replace('GPU Sort', 'GPU 排序')
    .replace('CPU Sort', 'CPU 排序')
    .replace('Worker Sort', 'Worker 排序');
}

export function localizeRuntimeMessage(language: UiLanguage, message?: string): string | undefined {
  if (!message || language === 'zh') return message;
  const directMessages: Readonly<Record<string, string>> = {
    '正在打开 RAW4D 文件': 'Opening RAW4D file',
    '正在读取 RAW4D 头部': 'Reading RAW4D header',
    '正在建立 4D 关键帧轨迹': 'Building 4D keyframe tracks',
    'RAW4D 解析完成': 'RAW4D parsing complete',
    '正在写入长期 GPUBuffer 并建立 GPU 解码路径': 'Uploading persistent GPU buffers and preparing GPU decode',
    '三维视口尚未初始化完成。': 'The 3D viewport is not ready.',
  };
  if (directMessages[message]) return directMessages[message];
  const gaussianProgress = /^正在读取高斯数据 (\d+)%$/.exec(message);
  if (gaussianProgress) return `Reading Gaussian data ${gaussianProgress[1]}%`;
  return message;
}
